DAILY_NOTES: tuple[str, ...] = tuple(
    dict.fromkeys(line.strip() for line in _RAW.splitlines() if line.strip())
)


def note_candidates(user_id: int, day, *, limit: int = 16) -> list[dict]:
    """Несколько далеко разнесённых фраз на дату.

    Клиент выбирает ту, которую этот человек не видел в последние недели.
    Один и тот же пользователь в один и тот же день получает один и тот же набор.
    """
    total = len(DAILY_NOTES)
    if total == 0:
        return []
    seed = (day.toordinal() + (int(user_id) % 997) * 17) % total
    step = max(1, total // max(limit, 1))
    seen: set[int] = set()
    out: list[dict] = []
    cursor = seed
    while len(out) < limit and len(seen) < total:
        if cursor not in seen:
            seen.add(cursor)
            out.append({"id": f"n{cursor}", "text": DAILY_NOTES[cursor]})
        nxt = (cursor + step) % total
        if nxt == cursor:
            break
        cursor = nxt
        if cursor == seed:
            break
    return out

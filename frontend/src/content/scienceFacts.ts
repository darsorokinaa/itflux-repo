export function pickScienceFact(random: () => number = Math.random): ScienceFact {
  const raw = Number(random());
  const unit = Number.isFinite(raw) ? Math.min(0.999999, Math.max(0, raw)) : 0;
  const index = Math.floor(unit * SCIENCE_FACTS.length);
  return SCIENCE_FACTS[index];
}

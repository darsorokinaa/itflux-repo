export function examVariantCopy(level?: string, subject?: string): ExamVariantCopy {
  const lv = String(level || "").toLowerCase();
  let sub = String(subject || "").toLowerCase();
  if (sub === "history") sub = "hist";
  if (sub === "prog") sub = "inf";
  if (lv === "vpr" || lv === "school") return VPR_COPY;
  return LEVEL_SUBJECT[`${lv}:${sub}`] || BY_SUBJECT[sub] || DEFAULT_COPY;
}

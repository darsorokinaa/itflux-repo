function ReportLinks({ links }: { links: ReportLink[] }) {
  return (
    <p className="xmas-links">
      {links.map((link, index) => (
        <span key={link.href}>
          {index > 0 ? " · " : null}
          <a href={link.href}>{link.label}</a>
        </span>
      ))}
    </p>
  );
}

function ReportCard({
  item,
  onOpen,
}: {
  item: Report;
  onOpen: (index: number) => void;
}) {
  const photo = item.photo;
  return (
    <article className="xmas-tl__item">
      <h3>{item.title}</h3>
      <p>{item.text}</p>
      {photo ? (
        <img
          className="xmas-tl__photo"
          src={charityImg(photo.file)}
          alt={photo.alt}
          onClick={() => onOpen(photo.lightIndex)}
        />
      ) : null}
      <ReportLinks links={item.links} />
    </article>
  );
}

export default function FundraiserReports({
  onOpen,
}: {
  onOpen: (index: number) => void;
}) {
  return (
    <>
      {REPORT_YEARS.map((group) => (
        <div key={group.year}>
          <div className="xmas-year">{group.year}</div>
          <div className="xmas-tl">
            {group.items.map((item) => (
              <ReportCard key={item.title} item={item} onOpen={onOpen} />
            ))}
          </div>
        </div>
      ))}
    </>
  );
}
